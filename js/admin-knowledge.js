/* ============================================================
   EVER NOVA LIFE — admin: what the chat agent knows

   The documents the chat bubble answers from, and the four ways
   to add one: a file from your machine, something you type, a
   page from the site, or the generated catalogue.

   Nothing here talks to ElevenLabs. The API key that would let it
   can rewrite every agent on the account, so it stays on the
   server and this page asks our own /api/admin/agent/knowledge.

   Own file for the same reason admin-inbox.js and
   admin-disputes.js are: admin-console.js is long enough, and an
   upload screen is a screen. Rendered wholesale on every state
   change, so no listeners are wired here — the console's
   delegated click handler calls back in by class name.
   ============================================================ */
(function (window, document) {
  'use strict';
  var A = window.Admin;

  var TYPE_LABEL = { url: 'Page', text: 'Note', file: 'File' };

  /* The two documents the sync button rewrites. Named so the list can say
     "regenerated, do not hand-edit" against them rather than letting
     someone carefully edit a file that the next sync will replace. */
  var GENERATED = ['Catalogue', 'Delivery and shipping'];

  function row(doc) {
    var generated = GENERATED.indexOf(doc.name) !== -1;
    return '' +
      '<div class="adm-kb-row">' +
        '<div class="adm-kb-main">' +
          '<span class="adm-kb-name">' + A.esc(doc.name || '(unnamed)') + '</span>' +
          '<span class="adm-kb-type">' + A.esc(TYPE_LABEL[doc.type] || doc.type) + '</span>' +
          (generated ? '<span class="adm-kb-auto">regenerated by Rebuild</span>' : '') +
        '</div>' +
        '<div class="adm-kb-actions">' +
          (doc.type === 'url'
            ? '<button class="btn btn-ghost act-kb-refresh" data-id="' + A.esc(doc.id) + '" ' +
              'data-name="' + A.esc(doc.name) + '">Refresh</button>'
            : '') +
          '<button class="btn btn-ghost act-kb-remove" data-id="' + A.esc(doc.id) + '" ' +
            'data-name="' + A.esc(doc.name) + '">Remove</button>' +
        '</div>' +
      '</div>';
  }

  function addPanel() {
    return '' +
      '<div class="adm-card">' +
        '<div class="adm-card-head"><h3>Add something</h3></div>' +

        '<div class="adm-kb-add">' +
          '<label for="kbFile">A file — PDF, text or markdown</label>' +
          '<div class="adm-kb-inline">' +
            '<input type="file" id="kbFile" accept=".pdf,.txt,.md,.markdown,text/plain,application/pdf">' +
            '<button class="btn btn-primary act-kb-file" type="button">Upload</button>' +
          '</div>' +
          '<p class="adm-note">Up to about 10MB. Scanned images will not read well — the agent needs text it can search.</p>' +
        '</div>' +

        '<div class="adm-kb-add">' +
          '<label for="kbNoteName">Something you type — hours, procedures, anything not on the site</label>' +
          '<input type="text" id="kbNoteName" placeholder="A short title, e.g. Handling times" maxlength="120">' +
          '<textarea id="kbNoteText" rows="5" placeholder="Write in plain sentences. The agent reads this as language, not as a form."></textarea>' +
          '<button class="btn btn-primary act-kb-text" type="button">Save note</button>' +
        '</div>' +

        '<div class="adm-kb-add">' +
          '<label for="kbPage">A page from the site</label>' +
          '<div class="adm-kb-inline">' +
            '<input type="text" id="kbPage" placeholder="faq.html" maxlength="200">' +
            '<button class="btn btn-primary act-kb-url" type="button">Add page</button>' +
          '</div>' +
          '<p class="adm-note">Read once, when you add it. Edit the page later and press Refresh, or the agent keeps quoting the old version.</p>' +
        '</div>' +
      '</div>';
  }

  function render(state, body) {
    var data = state.knowledge;

    if (!data) { body.innerHTML = '<div class="adm-card">' + A.skeleton(5) + '</div>'; return; }

    if (data.configured === false) {
      body.innerHTML =
        '<div class="adm-card">' +
          '<div class="adm-card-head"><h3>Not connected</h3></div>' +
          '<p class="adm-note" style="margin:0">' +
            'This server has no <code>ELEVENLABS_API_KEY</code>, so it cannot reach the ' +
            'knowledge base. Add it in Render under Environment, then reload this page. ' +
            'The chat itself keeps working without it — only this screen needs it.' +
          '</p>' +
        '</div>';
      return;
    }

    var docs = data.documents || [];
    body.innerHTML =
      '<div class="adm-card">' +
        '<div class="adm-card-head">' +
          '<h3>The agent answers from these</h3>' +
          '<button class="btn btn-ghost act-kb-sync" type="button">Rebuild catalogue &amp; delivery</button>' +
        '</div>' +
        (docs.length
          ? '<div class="adm-kb-list">' + docs.map(row).join('') + '</div>'
          : '<p class="adm-note" style="margin:0">Nothing yet. Add a file or a note below.</p>') +
        '<p class="adm-note">' +
          'Prices and stock are read live from this server every time a customer asks, ' +
          'so they are never stale. Press Rebuild after a price change and the catalogue ' +
          'document catches up too.' +
        '</p>' +
      '</div>' +
      addPanel();
  }

  window.AdminKnowledge = { render: render };
})(window, document);
